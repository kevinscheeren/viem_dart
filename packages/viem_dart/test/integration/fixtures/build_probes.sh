#!/bin/sh
# Regenerates capability_probes.dart (creation bytecode of the contracts in
# CapabilityProbes.sol). Needs Foundry's `forge`; pins solc 0.8.24 and the
# paris EVM so the output is reproducible. Run from packages/viem_dart.
set -eu
here="$(cd "$(dirname "$0")" && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
mkdir -p "$work/src"
cp "$here/CapabilityProbes.sol" "$work/src/"
cat > "$work/foundry.toml" <<'TOML'
[profile.default]
src = 'src'
solc_version = '0.8.24'
evm_version = 'paris'
optimizer = true
optimizer_runs = 200
via_ir = true
bytecode_hash = 'none'
cbor_metadata = false
TOML
# Lint warnings about the (deliberately simple) test contracts are noise;
# show the output only if the build fails.
out="$(cd "$work" && forge build 2>&1)" || { echo "$out" >&2; exit 1; }
{
  echo "// GENERATED by build_probes.sh from CapabilityProbes.sol — do not edit."
  echo "// ignore_for_file: lines_longer_than_80_chars"
  echo
  emit() { # contract name, Dart constant name
    code="$(forge inspect --root "$work" "$1" bytecode 2>/dev/null)"
    echo "/// Creation bytecode of \`$1\`."
    echo "const String $2 = '$code';"
    echo
  }
  emit Probe probeBytecode
  emit Aggregate3 aggregate3Bytecode
  emit Eip712Oracle eip712OracleBytecode
  emit Erc1271Wallet erc1271WalletBytecode
  emit Erc1271WrongMagic erc1271WrongMagicBytecode
  emit Erc1271Reverting erc1271RevertingBytecode
  emit Erc1271WalletFactory erc1271WalletFactoryBytecode
} > "$here/capability_probes.dart"
dart format "$here/capability_probes.dart" >/dev/null
