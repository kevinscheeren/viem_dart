import 'package:code_builder/code_builder.dart';
import 'package:viem_dart/abi.dart';

import 'abi_literal.dart';
import 'event_methods_builder.dart';
import 'name_utils.dart';
import 'type_mapping.dart';

/// [buildReadContractClass]'s result: the `<className>Contract` class
/// itself, plus the typed event-data classes (`<Event>Event`, one per ABI
/// event — see `event_methods_builder.dart`) its `get<Event>Events`/
/// `watch<Event>Event` methods return, which need to be emitted as their
/// own top-level declarations alongside it (not nested inside the class).
class ReadContractResult {
  const ReadContractResult({
    required this.contractClass,
    required this.eventClasses,
  });

  final Class contractClass;
  final List<Class> eventClasses;
}

/// Builds the read-only `<className>Contract` class: `{required
/// PublicClient client, required String address}` plus:
/// - one typed method per `view`/`pure` function in [functions], each
///   calling `PublicClient.readContract` (`ContractActions` extension, see
///   `lib/src/actions/public/contract_actions.dart`) and returning the
///   [TypeMapper]-mapped Dart type.
/// - a `get<Event>Events`/`watch<Event>Event` pair per ABI event in
///   [events] — see `event_methods_builder.dart`. Both are
///   `PublicClient`-only capabilities (`ContractActions`, not
///   `ContractWalletActions`), same as the runtime API's own split.
///
/// A function with more than one output returns a Dart record (named
/// fields, one per output) rather than a generated class: unlike a
/// Solidity `tuple`/struct (a *type* that can recur across many functions,
/// worth a shared named class — see [TypeMapper]), a function's own
/// multi-value return shape is unique to that one function, so a record —
/// Dart's own built-in anonymous product type — is the better fit; no
/// class-naming/dedup machinery needed for something used exactly once.
ReadContractResult buildReadContractClass({
  required String className,
  required List<AbiFunction> functions,
  required List<AbiEvent> events,
  required TypeMapper typeMapper,
}) {
  final readFunctions = functions
      .where((f) => f.stateMutability == 'view' || f.stateMutability == 'pure')
      .toList();
  final methodNames = uniqueNames(readFunctions.map((f) => f.name).toList());
  final eventMethods = buildEventMethods(events, typeMapper);

  final contractClass = Class(
    (b) => b
      ..name = '${className}Contract'
      ..docs.add(
        "/// Read-only typed bindings for the `$className` contract's ABI "
        '— generated by `viem_dart_builders` from its `@GenerateAbi` '
        'annotation. See `${className}WalletContract` for write methods.',
      )
      ..fields.addAll([
        Field(
          (f) => f
            ..name = 'client'
            ..modifier = FieldModifier.final$
            ..type = refer('PublicClient'),
        ),
        Field(
          (f) => f
            ..name = 'address'
            ..modifier = FieldModifier.final$
            ..type = refer('String'),
        ),
      ])
      ..constructors.add(
        Constructor(
          (c) => c
            ..constant = true
            ..optionalParameters.addAll([
              Parameter(
                (p) => p
                  ..name = 'client'
                  ..named = true
                  ..required = true
                  ..toThis = true,
              ),
              Parameter(
                (p) => p
                  ..name = 'address'
                  ..named = true
                  ..required = true
                  ..toThis = true,
              ),
            ]),
        ),
      )
      ..methods.addAll([
        for (var i = 0; i < readFunctions.length; i++)
          buildReadMethod(readFunctions[i], methodNames[i], typeMapper),
        ...eventMethods.contractMethods,
      ]),
  );

  return ReadContractResult(
    contractClass: contractClass,
    eventClasses: eventMethods.eventClasses,
  );
}

/// Builds a single typed read method for ABI function [fn], named
/// [methodName] (already disambiguated against sibling overloads — see
/// [uniqueNames]).
Method buildReadMethod(AbiFunction fn, String methodName, TypeMapper mapper) {
  final inputNames = uniqueNames(
    fn.inputs.map((p) => p.name).toList(),
    fallbackPrefix: 'arg',
  );
  final outputNames = fn.outputs.length > 1
      ? uniqueNames(
          fn.outputs.map((p) => p.name).toList(),
          fallbackPrefix: 'output',
        )
      : const <String>[];

  return Method(
    (m) => m
      ..name = methodName
      ..modifier = MethodModifier.async
      ..docs.add('/// Calls the `${fn.name}` view/pure function.')
      ..returns = TypeReference(
        (t) => t
          ..symbol = 'Future'
          ..types.add(_returnType(fn, outputNames, mapper)),
      )
      ..optionalParameters.addAll([
        for (var i = 0; i < fn.inputs.length; i++)
          Parameter(
            (p) => p
              ..name = inputNames[i]
              ..named = true
              ..required = true
              ..type = mapper.dartType(fn.inputs[i]),
          ),
        Parameter(
          (p) => p
            ..name = 'blockNumber'
            ..named = true
            ..type = refer('BigInt?'),
        ),
        Parameter(
          (p) => p
            ..name = 'blockTag'
            ..named = true
            ..type = refer('String')
            ..defaultTo = literalString('latest').code,
        ),
      ])
      ..body = _readMethodBody(fn, inputNames, outputNames, mapper),
  );
}

/// The Dart return type for [fn]'s output(s): `void` for none, the mapped
/// type directly for exactly one, or a named-field [RecordType] — Dart's
/// own built-in anonymous product type, no generated class needed — for
/// more than one (see [buildReadContractClass]'s doc comment for why a
/// record and not a shared generated class here).
Reference _returnType(
  AbiFunction fn,
  List<String> outputNames,
  TypeMapper mapper,
) {
  if (fn.outputs.isEmpty) return refer('void');
  if (fn.outputs.length == 1) return mapper.dartType(fn.outputs.single);
  return RecordType(
    (b) => b.namedFieldTypes.addEntries(
      List.generate(
        fn.outputs.length,
        (i) => MapEntry(outputNames[i], mapper.dartType(fn.outputs[i])),
      ),
    ),
  );
}

Code _readMethodBody(
  AbiFunction fn,
  List<String> inputNames,
  List<String> outputNames,
  TypeMapper mapper,
) {
  final argsList = inputNames.map((n) => n).join(', ');
  final callSource =
      'await client.readContract('
      'address: address, '
      'abi: ${_abiFunctionExprSource(fn)}, '
      'args: [$argsList], '
      'blockNumber: blockNumber, '
      'blockTag: blockTag)';

  if (fn.outputs.isEmpty) {
    return Code('$callSource;');
  }
  if (fn.outputs.length == 1) {
    return Code(
      'final raw = $callSource;\nreturn ${mapper.convertFromDecoded('raw', fn.outputs.single)};',
    );
  }
  final fields = List.generate(
    fn.outputs.length,
    (i) =>
        '${outputNames[i]}: ${mapper.convertFromDecoded('raw[$i]', fn.outputs[i])}',
  );
  return Code(
    'final raw = $callSource as List<Object?>;\n'
    'return (${fields.join(', ')});',
  );
}

/// Renders [abiFunctionLiteral]'s [Expression] to a raw Dart source string
/// for splicing into a [Code] template — [_readMethodBody] builds its
/// method body as one interpolated source string (simpler than composing
/// nested [Expression]s for a multi-statement body with an `await` and an
/// `if`-free single return), so the ABI literal needs to be a string too.
String _abiFunctionExprSource(AbiFunction fn) => abiFunctionLiteral(
  fn,
).accept(DartEmitter(useNullSafetySyntax: true)).toString();
