import 'package:code_builder/code_builder.dart';
import 'package:viem_dart/abi.dart';

import 'abi_literal.dart';
import 'name_utils.dart';
import 'type_mapping.dart';

/// Builds `<className>WalletContract extends <className>Contract`: one
/// typed method per `payable`/`nonpayable` function in [functions], each
/// calling `WalletClient.writeContract` (`ContractWalletActions`
/// extension) and returning `Future<String>` (the submitted transaction's
/// hash).
///
/// Mirrors the runtime `Contract`/`WalletContract` split
/// (`lib/src/contract/contract.dart`) so generated bindings stay
/// consistent with the nominal client typing: a `<className>Contract`
/// holding only a `PublicClient` never exposes write methods, only
/// `<className>WalletContract` (which requires a `WalletClient`) does.
Class buildWriteContractClass({
  required String className,
  required List<AbiFunction> functions,
  required TypeMapper typeMapper,
}) {
  final writeFunctions = functions
      .where(
        (f) =>
            f.stateMutability == 'payable' || f.stateMutability == 'nonpayable',
      )
      .toList();
  final methodNames = uniqueNames(writeFunctions.map((f) => f.name).toList());

  return Class(
    (b) => b
      ..name = '${className}WalletContract'
      ..extend = refer('${className}Contract')
      ..docs.add(
        "/// Write-capable typed bindings for the `$className` contract's "
        'ABI — generated by `viem_dart_builders`. Extends '
        '`${className}Contract` for its read methods; requires a '
        '`WalletClient` (not just a `PublicClient`) to construct.',
      )
      ..constructors.add(
        Constructor(
          (c) => c
            ..constant = true
            ..optionalParameters.addAll([
              Parameter(
                (p) => p
                  ..name = 'client'
                  ..named = true
                  ..required = true
                  ..type = refer('WalletClient'),
              ),
              Parameter(
                (p) => p
                  ..name = 'address'
                  ..named = true
                  ..required = true
                  ..type = refer('String'),
              ),
            ])
            ..initializers.add(
              const Code('super(client: client, address: address)'),
            ),
        ),
      )
      ..methods.add(
        Method(
          (m) => m
            ..name = '_walletClient'
            ..type = MethodType.getter
            ..returns = refer('WalletClient')
            ..lambda = true
            ..body = const Code('client as WalletClient'),
        ),
      )
      ..methods.addAll([
        for (var i = 0; i < writeFunctions.length; i++)
          buildWriteMethod(writeFunctions[i], methodNames[i], typeMapper),
      ]),
  );
}

/// Builds a single typed write method for ABI function [fn], named
/// [methodName] (already disambiguated against sibling overloads — see
/// [uniqueNames]).
Method buildWriteMethod(AbiFunction fn, String methodName, TypeMapper mapper) {
  final inputNames = uniqueNames(
    fn.inputs.map((p) => p.name).toList(),
    fallbackPrefix: 'arg',
  );
  final argsList = inputNames.join(', ');

  return Method(
    (m) => m
      ..name = methodName
      ..docs.add(
        '/// Calls the `${fn.name}` ${fn.stateMutability} function, '
        'signing and submitting the transaction.',
      )
      ..returns = TypeReference(
        (t) => t
          ..symbol = 'Future'
          ..types.add(refer('String')),
      )
      ..optionalParameters.addAll([
        for (var i = 0; i < fn.inputs.length; i++)
          Parameter(
            (p) => p
              ..name = inputNames[i]
              ..named = true
              ..required = true
              ..type = mapper.dartType(fn.inputs[i]),
          ),
        Parameter(
          (p) => p
            ..name = 'from'
            ..named = true
            ..type = refer('String?'),
        ),
        Parameter(
          (p) => p
            ..name = 'value'
            ..named = true
            ..type = refer('BigInt?'),
        ),
        Parameter(
          (p) => p
            ..name = 'gas'
            ..named = true
            ..type = refer('BigInt?'),
        ),
        Parameter(
          (p) => p
            ..name = 'maxFeePerGas'
            ..named = true
            ..type = refer('BigInt?'),
        ),
        Parameter(
          (p) => p
            ..name = 'maxPriorityFeePerGas'
            ..named = true
            ..type = refer('BigInt?'),
        ),
        Parameter(
          (p) => p
            ..name = 'nonce'
            ..named = true
            ..type = refer('int?'),
        ),
      ])
      ..lambda = true
      ..body = Code(
        '_walletClient.writeContract('
        'address: address, '
        'abi: ${_abiFunctionExprSource(fn)}, '
        'args: [$argsList], '
        'from: from, '
        'value: value, '
        'gas: gas, '
        'maxFeePerGas: maxFeePerGas, '
        'maxPriorityFeePerGas: maxPriorityFeePerGas, '
        'nonce: nonce)',
      ),
  );
}

/// See the identically-named helper in `read_contract_builder.dart` — same
/// rationale (an interpolated-string method body needs the ABI literal as
/// source text, not a nested `Expression`).
String _abiFunctionExprSource(AbiFunction fn) => abiFunctionLiteral(
  fn,
).accept(DartEmitter(useNullSafetySyntax: true)).toString();
