#!/bin/sh
# Regenerates lib/src/actions/public/erc6492_validator_bytecode.dart (the
# creation bytecode of Erc6492Validator.sol). Needs Foundry's `forge`; pins
# solc 0.8.24 and the paris EVM so the output is reproducible. Run from
# packages/viem_dart.
set -eu
here="$(cd "$(dirname "$0")" && pwd)"
out="$here/../../lib/src/actions/public/erc6492_validator_bytecode.dart"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
mkdir -p "$work/src"
cp "$here/Erc6492Validator.sol" "$work/src/"
cat > "$work/foundry.toml" <<'TOML'
[profile.default]
src = 'src'
solc_version = '0.8.24'
evm_version = 'paris'
optimizer = true
optimizer_runs = 200
via_ir = true
bytecode_hash = 'none'
cbor_metadata = false
TOML
result="$(cd "$work" && forge build 2>&1)" || { echo "$result" >&2; exit 1; }
code="$(forge inspect --root "$work" Erc6492Validator bytecode 2>/dev/null)"
{
  echo "// GENERATED by tool/erc6492_validator/build.sh from Erc6492Validator.sol — do not edit."
  echo "// ignore_for_file: lines_longer_than_80_chars"
  echo
  echo "/// Creation bytecode of \`Erc6492Validator\`, whose constructor takes"
  echo "/// \`(address signer, bytes32 hash, address factory, bytes factoryCalldata,"
  echo "/// bytes signature)\` and returns one word: 1 for a valid signature."
  echo "const String erc6492ValidatorBytecode = '$code';"
} > "$out"
dart format "$out" >/dev/null
