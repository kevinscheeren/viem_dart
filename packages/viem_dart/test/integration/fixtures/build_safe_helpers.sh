#!/bin/sh
# Regenerates safe_test_helpers.dart (creation bytecode of the contracts in
# SafeTestHelpers.sol). Needs Foundry's `forge`; pins the same compiler
# settings as build_probes.sh so the output is reproducible. Run from
# anywhere.
set -eu
here="$(cd "$(dirname "$0")" && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
mkdir -p "$work/src"
cp "$here/SafeTestHelpers.sol" "$work/src/"
cat > "$work/foundry.toml" <<'TOML'
[profile.default]
src = 'src'
solc_version = '0.8.24'
evm_version = 'paris'
optimizer = true
optimizer_runs = 200
via_ir = true
bytecode_hash = 'none'
cbor_metadata = false
TOML
out="$(cd "$work" && forge build 2>&1)" || { echo "$out" >&2; exit 1; }
{
  echo "// GENERATED by build_safe_helpers.sh from SafeTestHelpers.sol — do not edit."
  echo "// ignore_for_file: lines_longer_than_80_chars"
  echo
  emit() { # contract name, Dart constant name
    code="$(forge inspect --root "$work" "$1" bytecode 2>/dev/null)"
    echo "/// Creation bytecode of \`$1\`."
    echo "const String $2 = '$code';"
    echo
  }
  emit SafeSetupHelper safeSetupHelperBytecode
  emit EcdsaDomainVerifier ecdsaDomainVerifierBytecode
} > "$here/safe_test_helpers.dart"
dart format "$here/safe_test_helpers.dart" >/dev/null
